package ru.rasconsole.ras;

/** Какая авторизация нужна операции. */
public enum AuthKind {
    /** Без авторизации (список кластеров, версия агента). */
    NONE,
    /** Администратор центрального сервера (агента). */
    AGENT,
    /** Администратор кластера. */
    CLUSTER,
    /** Администратор кластера + пользователь информационной базы. */
    INFOBASE
}
